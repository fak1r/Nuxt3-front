import fs from 'fs'
import path from 'path'
import axios from 'axios'
import type { Producer, ProducerCatalogItem } from '~/types/categories.types'
import {
  GENERATED_ROUTES_PATH,
  GENERATED_LEGACY_PRODUCT_REDIRECTS_PATH,
  GENERATED_SITEMAP_IMAGES_PATH,
  STATIC_GENERATED_ROUTES,
  normalizePath,
  prepareGeneratedRoutes,
} from './generated-routes-manifest.js'

const API_BASE = process.env.NUXT_PUBLIC_API_BASE_URL || 'https://zampol.ru/api'
const api = axios.create({
  baseURL: API_BASE,
  proxy: false,
})
const IMAGE_FETCH_CONCURRENCY = 6

async function getCategories() {
  const { data } = await api.get('/products/categories')
  return data
}

async function getProducers() {
  const { data } = await api.get('/products/producers')
  return data
}

async function getCategoryCatalog(categorySlug: string) {
  const { data } = await api.get<ProducerCatalogItem[]>(`/products/${categorySlug}/catalog`)
  return data
}

async function getProducts(categorySlug: string, producerSlug: string) {
  const { data } = await api.get(`/products/${categorySlug}/${producerSlug}`, {
    params: {
      page: 1,
      limit: 9999,
    },
  })
  return data.items
}

async function getProductImages(productRoute: string) {
  const { data } = await api.get(`/products${productRoute}`)
  return getOriginalImageUrls(data.images)
}

function getOriginalImageUrls(images: unknown): string[] {
  if (!Array.isArray(images)) return []

  const urls = images
    .map((image) => {
      if (typeof image !== 'object' || image === null) return null

      const imageUrl = (image as { image_url?: unknown }).image_url
      if (typeof imageUrl !== 'string') return null

      try {
        const url = new URL(imageUrl)
        return url.protocol === 'https:' ? url.toString() : null
      } catch {
        return null
      }
    })
    .filter((imageUrl): imageUrl is string => imageUrl !== null)

  return [...new Set(urls)]
}

function getLegacyProductRoute(productRoute: string): string | null {
  const segments = normalizePath(productRoute).split('/').filter(Boolean)

  if (segments.length !== 4) return null

  const [categorySlug, producerSlug, , productSlug] = segments
  return `/${categorySlug}/${producerSlug}/${productSlug}`
}

function renderLegacyProductRedirects(redirects: Map<string, string>): string {
  const entries = [...redirects.entries()].sort(([legacyA], [legacyB]) => legacyA.localeCompare(legacyB))
  const lines = entries.map(
    ([legacyRoute, canonicalRoute]) =>
      `location = ${legacyRoute} { return 301 https://zampol.ru${canonicalRoute}$is_args$args; }`,
  )

  return ['# Generated by scripts/generate-routes.ts. Do not edit manually.', ...lines, ''].join('\n')
}

async function mapWithConcurrency<T, R>(
  items: T[],
  concurrency: number,
  mapper: (item: T) => Promise<R>,
): Promise<R[]> {
  const results = new Array<R>(items.length)
  let nextIndex = 0

  async function worker() {
    while (nextIndex < items.length) {
      const index = nextIndex++
      results[index] = await mapper(items[index])
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, worker))
  return results
}

async function generateRoutes() {
  const categories = await getCategories()
  const producers = await getProducers()
  const routes: string[] = [...STATIC_GENERATED_ROUTES]
  const productRoutes = new Set<string>()
  const legacyProductRedirects = new Map<string, string>()

  for (const category of categories) {
    routes.push(`/${category.slug}`)

    const relatedProducers = producers.filter((p: Producer) => p.category_id === category.id)
    let catalog: ProducerCatalogItem[] = []

    try {
      catalog = await getCategoryCatalog(category.slug)
    } catch (err: any) {
      console.warn(`Failed to load catalog for /${category.slug}: ${err.message}`)
    }

    for (const producer of relatedProducers) {
      const baseRoute = `/${category.slug}/${producer.slug}`
      routes.push(baseRoute)

      const producerCatalog = catalog.find((item) => item.slug === producer.slug)
      producerCatalog?.product_lines.forEach((line) => {
        routes.push(`${baseRoute}/${line.slug}`)
      })

      try {
        const products = await getProducts(category.slug, producer.slug)
        for (const product of products) {
          if (product.self) {
            const productRoute = normalizePath(product.self)
            routes.push(productRoute)
            productRoutes.add(productRoute)

            const legacyProductRoute = getLegacyProductRoute(productRoute)
            if (legacyProductRoute) {
              const existingTarget = legacyProductRedirects.get(legacyProductRoute)
              if (existingTarget && existingTarget !== productRoute) {
                throw new Error(`Legacy route collision: ${legacyProductRoute} maps to both ${existingTarget} and ${productRoute}`)
              }
              legacyProductRedirects.set(legacyProductRoute, productRoute)
            }
          }
        }
      } catch (err: any) {
        console.warn(`Failed to load products for ${baseRoute}: ${err.message}`)
      }
    }
  }

  const outputPath = path.resolve(GENERATED_ROUTES_PATH)
  const preparedRoutes = prepareGeneratedRoutes(routes)
  const productImages = await mapWithConcurrency([...productRoutes], IMAGE_FETCH_CONCURRENCY, async (productRoute) => {
    try {
      return { loc: productRoute, images: await getProductImages(productRoute) }
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error)
      console.warn(`Failed to load images for ${productRoute}: ${message}`)
      return { loc: productRoute, images: [] }
    }
  })
  const preparedSitemapImages = productImages
    .filter(({ loc, images }) => preparedRoutes.includes(loc) && images.length > 0)
    .sort((a, b) => a.loc.localeCompare(b.loc))

  fs.writeFileSync(outputPath, JSON.stringify(preparedRoutes, null, 2), 'utf-8')
  fs.writeFileSync(GENERATED_SITEMAP_IMAGES_PATH, JSON.stringify(preparedSitemapImages, null, 2), 'utf-8')
  fs.writeFileSync(GENERATED_LEGACY_PRODUCT_REDIRECTS_PATH, renderLegacyProductRedirects(legacyProductRedirects), 'utf-8')
  console.log(`Saved ${preparedRoutes.length} routes to ${outputPath}`)
  console.log(`Saved ${preparedSitemapImages.length} product image sets to ${GENERATED_SITEMAP_IMAGES_PATH}`)
  console.log(`Saved ${legacyProductRedirects.size} legacy product redirects to ${GENERATED_LEGACY_PRODUCT_REDIRECTS_PATH}`)
}

generateRoutes().catch((err) => {
  console.error('Route generation failed:', err)
})
